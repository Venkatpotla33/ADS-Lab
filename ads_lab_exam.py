# Red-Black Tree
R = "RED"; B = "BLACK"

class Node:
    def __init__(s,v): s.v=v; s.l=s.r=s.p=None; s.c=R

def rotL(t,x):
    y=x.r; x.r=y.l
    if y.l: y.l.p=x
    y.p=x.p
    if not x.p: t.root=y
    elif x==x.p.l: x.p.l=y
    else: x.p.r=y
    y.l=x; x.p=y

def rotR(t,x):
    y=x.l; x.l=y.r
    if y.r: y.r.p=x
    y.p=x.p
    if not x.p: t.root=y
    elif x==x.p.r: x.p.r=y
    else: x.p.l=y
    y.r=x; x.p=y

class RBT:
    def __init__(s): s.root=None

    def insert(s,v):
        n=Node(v)
        y=None; x=s.root
        while x:
            y=x
            x = x.l if n.v < x.v else x.r
        n.p=y
        if not y: s.root=n
        elif n.v < y.v: y.l=n
        else: y.r=n
        s.fix(n)

    def fix(s,n):
        while n.p and n.p.c==R:
            if n.p==n.p.p.l:
                u=n.p.p.r
                if u and u.c==R:
                    n.p.c=u.c=B; n.p.p.c=R; n=n.p.p
                else:
                    if n==n.p.r: n=n.p; rotL(s,n)
                    n.p.c=B; n.p.p.c=R; rotR(s,n.p.p)
            else:
                u=n.p.p.l
                if u and u.c==R:
                    n.p.c=u.c=B; n.p.p.c=R; n=n.p.p
                else:
                    if n==n.p.l: n=n.p; rotR(s,n)
                    n.p.c=B; n.p.p.c=R; rotL(s,n.p.p)
        s.root.c=B

    def inorder(s,n):
        if n: s.inorder(n.l); print(n.v,end=" "); s.inorder(n.r)

