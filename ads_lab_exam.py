class BTree:
    def __init__(s,t): s.t=t; s.root=["leaf",[],[]]  # [type,keys,children]

    def search(s,x,n=None):
        n=n or s.root
        i=0
        while i<len(n[1]) and x>n[1][i]: i+=1
        if i<len(n[1]) and x==n[1][i]: return True
        return False if n[0]=="leaf" else s.search(x,n[2][i])

    def split(s,p,i):
        t=s.t; y=p[2][i]
        z=["leaf"==y[0] and "leaf" or "node", y[1][t:], y[2][t:]]
        p[1].insert(i,y[1][t-1])
        p[2].insert(i,z)
        y[1],y[2]=y[1][:t-1],y[2][:t]

    def insert(s,x):
        r=s.root
        if len(r[1])==2*s.t-1:
            s.root=["node",[],[r]]
            s.split(s.root,0)
        s._ins(s.root,x)

    def _ins(s,n,x):
        if n[0]=="leaf":
            i=0
            while i<len(n[1]) and x>n[1][i]: i+=1
            n[1].insert(i,x)
        else:
            i=0
            while i<len(n[1]) and x>n[1][i]: i+=1
            if len(n[2][i][1])==2*s.t-1:
                s.split(n,i)
                if x>n[1][i]: i+=1
            s._ins(n[2][i],x)

