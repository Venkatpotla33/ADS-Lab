# AVL Tree
class Node:
    def __init__(s,v): s.v=v; s.l=s.r=None; s.h=1

def h(n): return n.h if n else 0
def bf(n): return h(n.l)-h(n.r)

def rotR(y):
    x=y.l; t=x.r
    x.r=y; y.l=t
    y.h=1+max(h(y.l),h(y.r))
    x.h=1+max(h(x.l),h(x.r))
    return x

def rotL(x):
    y=x.r; t=y.l
    y.l=x; x.r=t
    x.h=1+max(h(x.l),h(x.r))
    y.h=1+max(h(y.l),h(y.r))
    return y

def insert(n,v):
    if not n: return Node(v)
    if v<n.v: n.l=insert(n.l,v)
    else:     n.r=insert(n.r,v)

    n.h=1+max(h(n.l),h(n.r))
    b=bf(n)

    if b>1 and v<n.l.v: return rotR(n)       # LL
    if b<-1 and v>n.r.v: return rotL(n)       # RR
    if b>1 and v>n.l.v: n.l=rotL(n.l); return rotR(n)  # LR
    if b<-1 and v<n.r.v: n.r=rotR(n.r); return rotL(n) # RL

    return n

