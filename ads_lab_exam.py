from collections import deque

def insert(root, v):
    if not root: return Node(v)
    q=deque([root])
    while q:
        n=q.popleft()
        if not n.l: n.l=Node(v); break
        else: q.append(n.l)
        if not n.r: n.r=Node(v); break
        else: q.append(n.r)
    return root

